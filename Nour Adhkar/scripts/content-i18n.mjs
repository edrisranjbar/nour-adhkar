const FA_DIGITS = '۰۱۲۳۴۵۶۷۸۹'
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩'
export const num = (lang, n) => String(n).replace(/\d/g, d => (lang === 'ar' ? AR_DIGITS : FA_DIGITS)[d])

// Arabic counted nouns: 2 dual, 3-10 plural, 11-99 singular accusative, 100+ singular.
function arCount(n, { one, two, few, many, hundred }) {
  const v = Number(n) % 100 === 0 && Number(n) >= 100 ? 100 : Number(n)
  if (v === 1) return one
  if (v === 2) return two
  if (v >= 3 && v <= 10) return `${num('ar', n)} ${few}`
  if (v >= 11 && v <= 99) return `${num('ar', n)} ${many}`
  return `${num('ar', n)} ${hundred}`
}

