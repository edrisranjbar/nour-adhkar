export function fmtDate(lang, iso) {
  if (!iso) return ''
  const d = new Date(iso)
  if (lang === 'ar') return d.toLocaleDateString('ar-u-ca-gregory-nu-arab', { year: 'numeric', month: 'long', day: 'numeric' })
  const fa = d.toLocaleDateString('fa-IR-u-ca-persian', { year: 'numeric', month: 'long', day: 'numeric' })
  return lang === 'ckb' ? fa.replace(/[آ-ی]+/g, w => KU_MONTHS[w] || w) : fa
}

