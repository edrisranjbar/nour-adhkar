<?php

namespace Database\Seeders;

use App\Models\Post;
use App\Models\User;
use Illuminate\Database\Seeder;

/**
 * Two published articles shown in the Android app's «مقالات» screen (GET /api/posts).
 * Idempotent: re-running updates the same slugs. Only well-known, sourced texts are quoted.
 *
 *   php artisan db:seed --class=AppArticlesSeeder
 */
class AppArticlesSeeder extends Seeder
{
    public function run(): void
    {
        $author = User::where('role', 'admin')->orderBy('id')->first();
        if (!$author) {
            $this->command?->warn('No admin user found; create one first (AdminSeeder). Articles were not seeded.');
            return;
        }

        foreach ($this->articles() as $index => $article) {
            Post::updateOrCreate(
                ['slug' => $article['slug']],
                [
                    'title' => $article['title'],
                    'excerpt' => $article['excerpt'],
                    'content' => $article['content'],
                    'meta_title' => $article['title'] . ' | اذکار نور',
                    'meta_description' => $article['excerpt'],
                    'status' => 'published',
                    // Keep a stable order: the first article is the newest.
                    'published_at' => now()->subMinutes($index),
                    'user_id' => $author->id,
                ]
            );
        }
    }

